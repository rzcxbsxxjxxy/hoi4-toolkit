/**
 * 全量官方关键字(gen 为主 + 手写兜底)。
 *
 * 合并规则:同名以【gen】为准 —— gen 带官方作用域标注与出处手册,信息更全;
 * 手写种子只补 gen 里没有的名字,绝不覆盖 gen 的判定。
 */
export const OFFICIAL_ALL: OfficialEntry[] = (() => {
  const map = new Map<string, OfficialEntry>()
  // 1) 手写种子先入(★ 键必须与 gen 一致用小写,否则同名条目会漏合并成两份)
  for (const e of OFFICIAL_EFFECTS) map.set(e.name.toLowerCase(), { ...e, scopes: [], books: ['手写种子'] })
  for (const e of OFFICIAL_TRIGGERS) map.set(e.name.toLowerCase(), { ...e, scopes: [], books: ['手写种子'] })
  for (const e of OFFICIAL_SCOPES) map.set(e.name.toLowerCase(), { ...e, scopes: [], books: ['手写种子'] })
  // 2) gen 全量覆盖
  for (const e of GEN_OFFICIAL_ALL as readonly (OfficialEntry & { books: string[] })[]) {
    map.set(e.name.toLowerCase(), { name: e.name, type: e.type, summary: e.summary, scopes: e.scopes, books: e.books })
  }
  return [...map.values()]
})()

/** 名字 → 条目(小写键),供校验器做 O(1) 查表 */
export const OFFICIAL_BY_NAME: Map<string, OfficialEntry> = new Map(
  OFFICIAL_ALL.map((e) => [e.name.toLowerCase(), e]),
)
